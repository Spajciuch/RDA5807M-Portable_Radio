void show_frequency(float frequency_khz)
{
    // display.clearDisplay();
    // draw_ui();

    // rx.clearRdsBuffer();
    display.fillRect(0, 45, 130, -20, SH110X_BLACK);

    float frequency = frequency_khz / 100; // przygotuj do wyświetlenia w MHz
    char frequency_char[16];

    dtostrf(frequency, 3, 1, frequency_char); // podmień na char z jednym miejscem po przecinku

    display.fillRect(0, 0, 130, 15, SH110X_BLACK);
    display.setTextColor(SH110X_WHITE);
    display.setFont(&FreeMonoBold9pt7b);
    display.setTextSize(1);

    display.setCursor(10, 12);

    if (frequency_khz < 10000)
    {
        display.print(" ");
    }

    display.print(frequency_char);
    display.setTextSize(0.5);
    display.print(" MHz");
    display.display();
}

