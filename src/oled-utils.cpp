void show_power_screen(float voltage, float current, int precentage)
{
    float voltage_rounded = floor(voltage * 10 + 0.5) / 10; // zaokrąglanie do .x

    char voltage_char[16];
    dtostrf(voltage_rounded, 3, 1, voltage_char); // podmień na char z jednym miejscem po przecinku

    float current_mA = round(abs(current) * 1000);

    char current_char[16];
    dtostrf(current_mA, 3, 0, current_char);

    float watts = current * voltage;
    float watts_rounded = floor(abs(watts) * 10 + 0.5) / 10;

    char watts_char[16];
    dtostrf(watts_rounded, 3, 1, watts_char);

    display.setFont(&Neuropolitical_Rg7pt7b);
    display.setCursor(17, 11);
    display.print(voltage_char);
    display.setFont(&FreeMonoBold9pt7b);
    display.print("V");
    display.setFont(&Neuropolitical_Rg7pt7b);
    display.print(current);
    display.setFont(&FreeMonoBold9pt7b);
    display.print("mA");
    display.setFont(&Neuropolitical_Rg7pt7b);

    display.setCursor(17, 32);
    display.print(watts_char);
    display.setFont(&FreeMonoBold9pt7b);
    display.print("W");

    if (current > 0)
    {
        display.fillRect(3, 20, 7, 12, SH110X_BLACK);
        display.drawBitmap(3, 20, charging_indicator, 7, 12, SH110X_WHITE);
    }
    else
    {
        display.fillRect(3, 20, 7, 12, SH110X_BLACK);

        display.drawBitmap(3, 20, discharging_indicator, 7, 12, SH110X_WHITE);
        double pixels_precentage = precentage * (110.0 / 100.0);

        display.fillRect(3, 44, pixels_precentage, 12, SH110X_WHITE);
        display.display();
    }

    display.display();
}

